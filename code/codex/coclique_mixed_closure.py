"""Mixed defects propagate by a Sylvester equation after both blocks close.

This is an application of standard Krylov / graph controllability tools,
not a claim that asymmetry alone implies controllability or existence.
"""
from itertools import combinations
import sympy as sp

from coclique_residual_partition import Products


def walk_matrix(E):
    vector = sp.ones(E.rows, 1)
    columns = []
    for _ in range(E.rows):
        columns.append(vector)
        vector = E*vector
    return sp.Matrix.hstack(*columns)


def certify(B, D, E, k=14, mu=2, known_rows=()):
    B, D, E = map(sp.Matrix, (B, D, E))
    b, m = B.rows, E.rows
    A = B.row_join(D).col_join(D.T.row_join(E))
    assert A == A.T and all(A[i,i] == 0 for i in range(b+m))
    assert all(x in (0, 1) for x in A)
    assert A*sp.ones(b+m,1) == k*sp.ones(b+m,1)
    assert k*k+k == k-mu+mu*(b+m)
    defect = A*A+A-(k-mu)*sp.eye(b+m)-mu*sp.ones(b+m)
    assert defect[:b,:b].is_zero_matrix and defect[b:,b:].is_zero_matrix
    G = defect[:b,b:]
    assert B*G == G*E
    assert (G*sp.ones(m,1)).is_zero_matrix and (G.T*sp.ones(b,1)).is_zero_matrix
    W = walk_matrix(E)
    assert (G*W).is_zero_matrix
    determinant = W.det()
    report = dict(residual_walk_determinant=str(determinant),
                  residual_walk_dimension=int(W.rank()), residual_size=m,
                  full_mixed_verified=bool(G.is_zero_matrix),
                  completion_forced_by_residual_walks=bool(determinant != 0))
    if determinant:
        assert G.is_zero_matrix
    if known_rows:
        # Block Krylov space generated by already exact mixed rows.
        assert G.extract(known_rows, range(m)).is_zero_matrix
        space = sp.eye(b).extract(range(b), known_rows).row_join(sp.ones(b,1))
        space = sp.Matrix.hstack(*space.columnspace())
        dimensions = [space.cols]
        while space.cols < b:
            enlarged = space.row_join(B*space)
            next_space = sp.Matrix.hstack(*enlarged.columnspace())
            if next_space.cols == space.cols:
                break
            space = next_space
            dimensions.append(space.cols)
        assert (G.T*space).is_zero_matrix
        report.update(known_rows=list(known_rows), border_control_dimensions=dimensions,
                      completion_forced_by_border_control=space.cols == b)
    if not G.is_zero_matrix:
        # A nonzero real intertwiner requires a common eigenvalue.
        t = sp.Symbol('t')
        common = sp.gcd(B.charpoly(t).as_expr(), E.charpoly(t).as_expr())
        assert sp.degree(common, t) > 0
        report.update(common_characteristic_factor=str(common), mixed_defect=[list(map(int,G.row(i))) for i in range(b)])
    return report


def add_leaf_columns(model, B, M, edge):
    """If e has residual degree 1, its sole residual neighbour is f.

The complete mixed equation simplifies to (B+I)D_e+D_f=2*1.
For both leaves, subtracting gives B(D_e-D_f)=0. No fixed boundary
or leaf orientation is assumed. Products are exact Boolean ANDs.
"""
    indices = {v.name:i for i,v in enumerate(model.proto.variables)
               if v.name.startswith('v10_degree')}
    mul = Products(model, prefix='leaf_product')
    equations = 0
    for u, v in ((37,38), (38,37)):
        degree = model.get_int_var_from_proto_index(indices[f'v10_degree{u}'])
        leaf = model.new_bool_var(f'v10_leaf{u}')
        model.add(degree == 1).only_enforce_if(leaf)
        model.add(degree >= 2).only_enforce_if(leaf.Not())
        for b in B:
            if b in range(25):
                continue  # C and H mixed rows already exact.
            model.add(sum(mul(edge(b,w),edge(w,u)) for w in B)
                      +edge(b,u)+edge(b,v) == 2).only_enforce_if(leaf)
            equations += 1
    return dict(conditional_leaf_mixed_equations=equations,
                leaf_product_variables=len(mul.cache))
