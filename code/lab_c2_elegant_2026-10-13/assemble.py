TOT = {}
def add_group(name, lids):
    vc = collections.Counter(); pairs = 0
    for l in lids:
        p = LAT[l].get("primary")
        if p: vc.update(p["verdict_counts"]); pairs += p["pairs"]
    cl = collections.Counter(); kd = collections.Counter()
    for v, n in vc.items():
        c, k = K.classify(v); cl[c] += n; kd[k] += n
    sub = kd["a"] + kd["b"] + kd["inc"] + kd["other"]
    TOT[name] = {"lattices": len(lids), "lattices_with_pair_records": sum(1 for l in lids if LAT[l].get("primary")), "pairs": pairs, "verdict_counts": dict(vc),
                 "class_counts": dict(cl), "kind_counts": dict(kd), "substantive_pairs_a_plus_b_plus_inc": sub,
                 "share_of_all_pairs": {c: round(n / pairs, 6) for c, n in cl.items()} if pairs else {},
                 "share_of_substantive": {c: round(n / sub, 6) for c, n in cl.items() if K.classify_name_kind(c) in ("a", "b", "inc")} if False else None}
