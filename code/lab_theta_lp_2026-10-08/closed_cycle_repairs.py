"""C1, lab session, 2026-10-09. Closed transport cycles of length m with ONE extra relation (an extra edge or an
identification of two roles), tested with support_masks.verdict (local axioms, exact one-vertex spectral filters,
multiplicity system; float LP indication).   python closed_cycle_repairs.py <m> <cylinder|moebius> [edges|ident|all]"""
import sys, itertools, collections, time
import support_masks as S
m = int(sys.argv[1]); MO = sys.argv[2] == "moebius"; PART = sys.argv[3] if len(sys.argv) > 3 else "all"
names = ["a%d" % i for i in range(m)] + ["b%d" % i for i in range(m)] + ["c%d" % i for i in range(m)]; ix = {s: i for i, s in enumerate(names)}
E0 = []
for i in range(m):
    if i < m - 1 or not MO: an, bn = "a%d" % ((i + 1) % m), "b%d" % ((i + 1) % m)
    else: an, bn = "b0", "a0"
    for x, y in (("c%d" % i, "a%d" % i), ("c%d" % i, an), ("a%d" % i, an), ("c%d" % i, "b%d" % i), ("c%d" % i, bn), ("b%d" % i, bn)): E0.append((ix[x], ix[y]))
n = len(names); base = set(tuple(sorted(e)) for e in E0)
# symmetries of the ribbon graph, to list one representative per class: computed as automorphisms generated by the shift and the reflection and the strand swap
def shift(s):
    t, i = s[0], int(s[1:])
    if MO and t in "ab" and i == m - 1: return ("b" if t == "a" else "a") + "0"
    return "%s%d" % (t, (i + 1) % m)
def swap(s): return (("b" if s[0] == "a" else "a") if s[0] in "ab" else "c") + s[1:]
def refl(s):
    t, i = s[0], int(s[1:])
    if t == "c": return "c%d" % ((-i - 1) % m)
    j = (-i) % m
    if MO and i != 0: t = "b" if t == "a" else "a"
    return "%s%d" % (t, j)
gens = [shift, swap, refl]
def is_aut(f):
    return all(tuple(sorted((ix[f(names[p])], ix[f(names[q])]))) in base for p, q in E0)
gens = [g for g in gens if is_aut(g)]
def orbit_key(x, y):
    seen = {(x, y)}; st = [(x, y)]
    while st:
        p, q = st.pop()
        for g in gens:
            r = (g(p), g(q))
            if r not in seen: seen.add(r); st.append(r)
    return min(tuple(sorted(r)) for r in seen)
print("m = %d, %s: %d roles, %d symmetry generators used; clean cycle: %s" % (m, sys.argv[2], n, len(gens), S.verdict(n, E0)["status"]), flush=True)
t0 = time.time(); tally = collections.Counter(); done = set()
for kind in ("edges", "ident"):
    if PART not in ("all", kind): continue
    done = set()
    for x, y in itertools.combinations(names, 2):
        if tuple(sorted((ix[x], ix[y]))) in base: continue
        k_ = orbit_key(x, y)
        if k_ in done: continue
        done.add(k_)
        if kind == "edges":
            r = S.verdict(n, E0 + [(ix[x], ix[y])])
        else:
            keep = [s for s in names if s != y]; jx = {s: i for i, s in enumerate(keep)}; jx[y] = jx[x]; E = set()
            for p, q in E0:
                u, v = jx[names[p]], jx[names[q]]
                if u == v: E = None; break
                E.add((min(u, v), max(u, v)))
            r = {"status": "LOCAL"} if E is None else S.verdict(len(keep), sorted(E))
        tally[(kind, r["status"].split(" (")[0])] += 1
        if r["status"] not in ("NOT PSD", "LOCAL"): print("   %s %s %s : %s (masks %d)  [%.0f s]" % (x, "-" if kind == "edges" else "=", y, r["status"], r["masks"], time.time() - t0), flush=True)
print("summary:", dict(sorted(tally.items())))
