"""Arithmetic (discriminant) test for label sets of full rank (15/10/2026).

Fact (DISC).  In a Conway graph, fix v.  T (84 x 84) satisfies T^2 = 7T (P1), so T/7 is the orthogonal projection onto
V = range T (dim 30), and the lattice generated by the 84 label vectors with Gram 8T is sqrt(56) P_V(Z^84).  Since
P_V(Z^84) is the dual of the primitive lattice Z^84 n V,  disc(Lambda_8T) * disc(Z^84 n V) = 56^30 = 2^90 7^30, two
positive integers, so disc(Lambda_8T) = 2^a 7^b.  If a set S of labels has rank T_S = 30, its lattice Lambda_S has
finite index k in Lambda_8T, hence disc(Lambda_S) = 2^a 7^b k^2: every prime p other than 2 and 7 divides
disc(Lambda_S) to an EVEN power.  The same argument for U = 7 Pi - T (U^2 = 7U, rank 40) gives:
if rank U_S = 40 then disc(Lambda_S, cU) = (primes of 7c) x k^2, with cU integral.
(Scale: c U with c the least common denominator of U_S; the allowed primes are those of 7c.)
This script computes disc(Lambda_S) exactly: H = Gram of 30 (resp. 40) independent vectors, coordinates of the
others, index of the generated lattice (Hermite reduction), disc = det H / index^2.
usage: python disc_test.py <json with labels, edges> [stars, default 0,1,2,3] [key:index for a record]
"""
import json
import math
import sys
from fractions import Fraction as Fr

from ext4 import kval, Pi, rref_kernel


def det_frac(M):
    A = [[Fr(x) for x in row] for row in M]
    n = len(A)
    det = Fr(1)
    for c in range(n):
        p = next((i for i in range(c, n) if A[i][c] != 0), None)
        if p is None:
            return Fr(0)
        if p != c:
            A[c], A[p] = A[p], A[c]
            det = -det
        det *= A[c][c]
        for i in range(c + 1, n):
            if A[i][c] != 0:
                f = A[i][c] / A[c][c]
                A[i] = [x - f * y for x, y in zip(A[i], A[c])]
    return det


def solve(H, b):
    n = len(H)
    A = [[Fr(H[i][j]) for j in range(n)] + [Fr(b[i])] for i in range(n)]
    for c in range(n):
        p = next(i for i in range(c, n) if A[i][c] != 0)
        A[c], A[p] = A[p], A[c]
        pv = A[c][c]
        A[c] = [x / pv for x in A[c]]
        for i in range(n):
            if i != c and A[i][c] != 0:
                f = A[i][c]
                A[i] = [x - f * y for x, y in zip(A[i], A[c])]
    return [A[i][n] for i in range(n)]


def index_in_Zn(rows, n):
    """Index in Z^n of the lattice generated by integer row vectors (full rank n), by Hermite reduction."""
    rows = [list(r) for r in rows if any(r)]
    det = 1
    for c in range(n):
        # gcd-combine all rows with a nonzero entry in column c (among the remaining rows)
        piv = None
        while True:
            nz = [r for r in rows if r[c] != 0]
            if not nz:
                return 0
            nz.sort(key=lambda r: abs(r[c]))
            piv = nz[0]
            done = True
            for r in nz[1:]:
                q = r[c] // piv[c]
                for j in range(c, n):
                    r[j] -= q * piv[j]
                if r[c] != 0:
                    done = False
            rows = [r for r in rows if any(r)]
            if done:
                break
        det *= abs(piv[c])
        rows = [r for r in rows if r is not piv]
    return det


def lattice_disc(M, r):
    """M: symmetric Fraction Gram matrix (integral) of rank r. Returns disc of the lattice its vectors generate."""
    n = len(M)
    I = []
    for i in range(n):
        cand = I + [i]
        if det_frac([[M[a][b] for b in cand] for a in cand]) != 0:
            I.append(i)
        if len(I) == r:
            break
    assert len(I) == r
    H = [[M[a][b] for b in I] for a in I]
    dH = det_frac(H)
    coords = [solve(H, [M[a][j] for a in I]) for j in range(n) if j not in I]
    D = 1
    for c in coords:
        for x in c:
            D = D * x.denominator // math.gcd(D, x.denominator)
    rows = [[int(x * D) for x in c] for c in coords] + [[D if i == j else 0 for j in range(r)] for i in range(r)]
    sub = index_in_Zn(rows, r)  # index of D*Lambda in Z^r (coordinates w.r.t. the I-basis)
    idx = Fr(D ** r, sub)       # [Lambda : Lambda_I]
    assert idx.denominator == 1
    disc = dH / (idx * idx)
    return dH, int(idx), disc


def odd_part(N, allowed):
    N = abs(N)
    for p in allowed:
        while N % p == 0:
            N //= p
    return N


def small_factors(N, bound=100000):
    f = {}
    p = 2
    while p <= bound and N > 1:
        while N % p == 0:
            f[p] = f.get(p, 0) + 1
            N //= p
        p += 1 if p == 2 else 2
    return f, N


def main():
    d = json.load(open(sys.argv[1]))
    stars = tuple(int(t) for t in (sys.argv[2] if len(sys.argv) > 2 else "0,1,2,3").split(","))
    if len(sys.argv) > 3:
        key, _, k = sys.argv[3].partition(":")
        edges = d[key][int(k)]["edges"] if k else d[key]["edges"]
    else:
        edges = d["edges"]
    S = [frozenset(l) for l in d["labels"]]
    n = len(S)
    G = [[0] * n for _ in range(n)]
    for i, j in edges:
        G[i][j] = G[j][i] = 1
    T8 = [[8 * ((3 if i == j else 0) - G[i][j] - kval(S[i], S[j])) for j in range(n)] for i in range(n)]
    assert all(x.denominator == 1 for row in T8 for x in row)
    rT, _ = rref_kernel(T8)
    print("labels %d, rank T = %d" % (n, rT))
    if rT == 30:
        dH, idx, disc = lattice_disc(T8, 30)
        assert disc.denominator == 1
        disc = int(disc)
        rest = odd_part(disc, (2, 7))
        sq = math.isqrt(rest) ** 2 == rest
        f, cof = small_factors(disc)
        print("T-lattice (Gram 8T): disc = %d" % disc)
        print("   factorisation (primes < 1e5): %s, cofactor %d" % (f, cof))
        print("   part prime to 14 = %d, perfect square: %s  ->  (DISC-T) %s"
              % (rest, sq, "passes" if sq else "FAILS: S cannot have rank 30 inside a Conway graph"))
    else:
        print("rank T < 30: (DISC-T) does not apply")
    Uf = [[7 * Pi(S[i], S[j]) - ((3 if i == j else 0) - G[i][j] - kval(S[i], S[j])) for j in range(n)]
          for i in range(n)]
    c = 1
    for row in Uf:
        for x in row:
            c = c * x.denominator // math.gcd(c, x.denominator)
    Uc = [[c * x for x in row] for row in Uf]
    rU, _ = rref_kernel(Uc)
    print("rank U = %d (scale %d U is integral)" % (rU, c))
    if rU == 40:
        dH, idx, disc = lattice_disc(Uc, 40)
        assert disc.denominator == 1
        disc = int(disc)
        allowed = tuple(p for p in (2, 3, 5, 7, 11, 13) if (7 * c) % p == 0)
        rest = odd_part(disc, allowed)
        sq = math.isqrt(rest) ** 2 == rest
        f, cof = small_factors(disc)
        print("U-lattice (Gram %dU): disc = %d" % (c, disc))
        print("   factorisation (primes < 1e5): %s, cofactor %d" % (f, cof))
        print("   part prime to %s = %d, perfect square: %s  ->  (DISC-U) %s"
              % (allowed, rest, sq, "passes" if sq else "FAILS"))


if __name__ == "__main__":
    main()
