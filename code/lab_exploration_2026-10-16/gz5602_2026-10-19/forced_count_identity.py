"""Second-order identity on forced counts (LAB 19/10/2026).
For a vector c on the 21 rectangles with c in W (span of the grid and block relation vectors, so H c = 0), every label
w satisfies  sum_F c_F z_w(F) = sum_F c_F base(w, F)  (h = base - z).  For a 0/1 vector c = 1_P (P a union of
rectangles, e.g. a grid, a block at a root, an opposite pair) the count vector f_P = A 1_P is therefore FORCED on all
99 vertices: 0 at the root, 2 #{F in P containing the line of l} at a letter l, sum_{F in P} base(w, F) at a label w.
A^2 = 12 I - A + 2 J then requires, for any two such parts P, P':
      f_P . f_P'  =  12 |P cap P'| - 1_P . f_P'  + 2 |P| |P'|        (sizes in labels, 4 per rectangle).
A failure is an exact contradiction for the template (no solver).  The script tests every pair of parts generated by
the grids, the blocks and the opposite pairs of the template.
usage: python forced_count_identity.py <catalogue.json.gz> <open.tsv | all>"""
import gzip
import json
import sys
from collections import Counter
from fractions import Fraction
from itertools import combinations

recs = json.load(gzip.open(sys.argv[1]))["open"]
sel = None if sys.argv[2] == "all" else {int(l.split()[1]) for l in open(sys.argv[2]) if l.startswith("gz")}
RECT = list(combinations(range(7), 2))


def base(q, f):
    return 2 if f == q else (0 if set(f) & set(q) else 1)


def fvec(P):
    """forced counts of a union P of rectangles: (letter counts, label counts by rectangle class)"""
    let = [2 * sum(1 for F in P if a in F) for a in range(7)]      # same for both letters of the line a
    lab = {q: sum(base(q, F) for F in P) for q in RECT}
    return let, lab


def dot(P, Q):
    lp, bp = fvec(P); lq, bq = fvec(Q)
    return 2 * sum(lp[a] * lq[a] for a in range(7)) + 4 * sum(bp[q] * bq[q] for q in RECT)


def check(P, Q):
    inter = 4 * len(set(P) & set(Q))
    _, bq = fvec(Q)
    one_f = 4 * sum(bq[q] for q in P)
    return dot(P, Q) == 12 * inter - one_f + 2 * (4 * len(P)) * (4 * len(Q))


bad = Counter(); tested = 0; fails = []
for idx, r in enumerate(recs):
    if sel is not None and idx not in sel:
        continue
    t = r["template"]
    ng = {tuple(e) for e in t["nongrid_edges"]}
    parts = [(q,) for q in RECT if q not in ng]                      # grids
    for a, groups in enumerate(t["nontrivial_component_groups"]):
        for P in groups:
            parts.append(tuple(sorted(tuple(sorted((a, j))) for j in P)))
    parts = sorted(set(parts))
    tested += 1
    ok = True
    for P, Q in combinations(parts, 2):
        if not check(P, Q):
            ok = False; fails.append((idx, P, Q)); break
    if ok:
        for P in parts:
            if not check(P, P):
                ok = False; fails.append((idx, P, P)); break
    bad[ok] += 1
print("templates tested", tested, "identity holds for all part pairs:", dict(bad))
print("first failures:", fails[:10])
