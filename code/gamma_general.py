r"""Finish line (C), C1 27/09: Gamma = Aut(U)/W(R) for an envelope U of ANY root rank (generalises gamma_fullrank.py).
For rank < 24 a Dynkin automorphism phi of R is completed by an isometry psi of V_perp = span(R)-perp (dim d <= 4) preserving
the projection lattice P_perp(U); the pair is kept iff (phi + psi)(U) = U exactly.  Original header follows.

Aut(U) = W(R) x| Gamma, Gamma = stabiliser of the fundamental chamber = the Dynkin-diagram automorphisms phi (permutations of the
simple roots preserving the Cartan matrix) whose linear extension maps U onto U.  phi is determined by a bijection between
components of the same type and a diagram automorphism of each component.  Search: backtracking over the components, pruned by
the glue code (classes of U in D = sum R_i*/R_i: the projection of the glue code on the processed components must be mapped into
the projection on their images); final exact check phi(U) = U.
Output: list of Gamma elements as permutations of the simple roots (and the induced integer matrices on U's basis).
Check: |Gamma| against the 'group' field of Borcherds' table."""
import itertools, json, math, os, sys, time
from fractions import Fraction as F
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from y_pairs import setup as ysetup, root_system
from envelope_trap import inverse_exact


def diagram_automorphisms(A):
    """all permutations p of range(n) with A[p[i], p[j]] == A[i, j] (small components: brute force with pruning)."""
    n = len(A)
    out = []
    p = [-1] * n
    used = [False] * n

    def rec(i):
        if i == n:
            out.append(tuple(p)); return
        for t in range(n):
            if used[t] or A[t, t] != A[i, i]:
                continue
            if all(A[p[k], t] == A[k, i] for k in range(i)):
                p[i] = t; used[t] = True
                rec(i + 1)
                used[t] = False; p[i] = -1
    rec(0)
    return out


def comp_signature(A):
    n = len(A)
    degs = sorted(int((A[i] != 0).sum()) - 1 for i in range(n))
    return (n, tuple(degs))


def main():
    rec_ = json.load(open(sys.argv[1]))
    t0 = time.time()
    B, Gi, Bf, R, X3, Snew = ysetup(rec_['gens'])
    S, comp, marks, A, P = root_system(R)
    rank = len(S)
    d_perp = 24 - rank
    comps = [list(c) for c in comp]
    Acomp = [A[np.ix_(c, c)] for c in comps]
    sig = [comp_signature(a) for a in Acomp]
    dauts = [diagram_automorphisms(a) for a in Acomp]
    # labels of U's basis vectors: c_j = (b, alpha_j); class in D_i: c|_i * A_i^-1 mod 1
    Lab = np.rint(Bf @ S.T).astype(np.int64)                        # 24 basis vectors x 24 simple roots
    Ainv = [inverse_exact([[int(x) for x in row] for row in a]) for a in Acomp]

    def cls(i, labs):
        v = [sum(F(int(labs[a])) * Ainv[i][a][b] for a in range(len(comps[i]))) for b in range(len(comps[i]))]
        return tuple(x - math.floor(x) for x in v)
    # glue code: all classes of U (generated by the basis vectors), as tuples of per-component classes
    gens = [tuple(cls(i, Lab[k, comps[i]]) for i in range(len(comps))) for k in range(24)]
    add = lambda g, h: tuple(tuple((x + y) - math.floor(x + y) for x, y in zip(a, b)) for a, b in zip(g, h))
    zero = tuple(tuple(F(0) for _ in c) for c in comps)
    G = {zero}
    frontier = [zero]
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens:
                s = add(g, h)
                if s not in G:
                    G.add(s); nxt.append(s)
        frontier = nxt
    Glist = list(G)
    # a component map (i -> j with diagram iso q: simple root a of comp i -> simple root q[a] of comp j) acts on classes:
    # labels c (on comp i) go to labels c' on comp j with c'[q[a]] = c[a]; class is c' * A_j^-1 (A_j = A_i up to q)
    def map_class(i, j, q, x):
        # x is the class (vector mod 1 in the fundamental-weight dual coords) = c A_i^-1; recover c mod rows of A_i: c = x A_i
        n = len(comps[i])
        c = [sum(x[b] * int(Acomp[i][b, a]) for b in range(n)) for a in range(n)]
        c2 = [F(0)] * n
        for a in range(n):
            c2[q[a]] = c[a]
        v = [sum(c2[a] * Ainv[j][a][b] for a in range(n)) for b in range(n)]
        return tuple(y - math.floor(y) for y in v)
    ncomp = len(comps)
    order = sorted(range(ncomp), key=lambda i: -len(comps[i]))
    # integer indexing of the classes that occur in G's projections; lookup tables for the class maps
    elems = [sorted({g[i] for g in Glist}) for i in range(ncomp)]
    eidx = [{e: k for k, e in enumerate(el)} for el in elems]
    Gint = [tuple(eidx[i][g[i]] for i in range(ncomp)) for g in Glist]
    iso_cache = {}

    def perm_iso(Ai, Aj):
        n = len(Ai)
        p = [-1] * n; used = [False] * n; res = []

        def r(a):
            if a == n:
                res.append(tuple(p)); return
            for tt in range(n):
                if used[tt] or Aj[tt, tt] != Ai[a, a]:
                    continue
                if all(Aj[p[k], tt] == Ai[k, a] for k in range(a)):
                    p[a] = tt; used[tt] = True; r(a + 1); used[tt] = False; p[a] = -1
        r(0)
        return res

    def isos(i, j):
        if (i, j) not in iso_cache:
            iso_cache[(i, j)] = perm_iso(Acomp[i], Acomp[j])
        return iso_cache[(i, j)]
    table_cache = {}

    def ctable(i, j, q):
        key = (i, j, q)
        if key not in table_cache:
            tab = []
            for e in elems[i]:
                m = map_class(i, j, q, e)
                tab.append(eidx[j].get(m, -1))
            table_cache[key] = tab
        return table_cache[key]
    sols = []
    assign = {}
    usedj = set()

    def rec(t):
        if t == ncomp:
            sols.append(dict(assign)); return
        i = order[t]
        keys = [order[s] for s in range(t + 1)]
        for j in range(ncomp):
            if j in usedj or sig[j] != sig[i]:
                continue
            for q in isos(i, j):
                tab = ctable(i, j, q)
                if -1 in tab:
                    continue
                assign[i] = (j, q, tab)
                usedj.add(j)
                imgs = [assign[k][0] for k in keys]
                img_proj = {tuple(g[k] for k in imgs) for g in Gint}
                ok = True
                for g in Gint:
                    if tuple(assign[k][2][g[k]] for k in keys) not in img_proj:
                        ok = False; break
                if ok:
                    rec(t + 1)
                usedj.discard(j)
                del assign[i]

    rec(0)
    # exact check (phi + psi)(U) = U, psi an isometry of V_perp preserving P_perp(U)
    Binv = np.linalg.inv(Bf)
    Sm = S                                                             # rank x 24
    if d_perp:
        # psi runs over Aut(U cap V_perp) (necessary: phi + psi preserves V_perp and U); exact kernel lattice by HNF
        from envelope_trap import hnf_rows
        from h_stage2 import short_vectors_fast
        _, _, Vt = np.linalg.svd(Sm)
        Wp = Vt[rank:]                                                  # orthonormal basis of V_perp (d x 24)
        Mk = np.rint(Bf @ Sm.T).astype(np.int64)                        # (b_i, alpha_j)
        rows = [[int(Mk[i, j]) for j in range(rank)] + [int(i == t) for t in range(24)] for i in range(24)]
        Hh = hnf_rows(rows)
        Kc = np.array([row[rank:] for row in Hh if not any(row[:rank])], dtype=np.int64)   # d x 24 coefficients
        assert len(Kc) == d_perp
        # LLL-reduce the rootless sublattice (the HNF basis has large norms: the short-vector search below would explode)
        from envelope_trap import lll as _lll
        Kq = [[sum(F(int(Kc[i][k])) * B[k][t] for k in range(24)) for t in range(24)] for i in range(d_perp)]
        Kr = _lll(Kq)
        Kc = np.rint(np.array([[float(v) for v in row] for row in Kr]) @ np.linalg.inv(Bf)).astype(np.int64)
        GK = Kc @ np.array(Gi, dtype=np.int64) @ Kc.T                  # integer Gram of U cap V_perp (reduced basis)
        assert round(abs(np.linalg.det(GK.astype(float)))) == round(abs(np.linalg.det((np.array([[float(v) for v in row] for row in Kq]) @ np.array([[float(v) for v in row] for row in Kq]).T))))
        Kv = Kc.astype(float) @ Bf                                      # d x 24 vectors
        Kp = Kv @ Wp.T                                                  # d x d coordinates in Wp
        maxn = int(np.max(np.diag(GK)))
        X, nrm = short_vectors_fast(GK.tolist(), maxn)
        vecs = [(x, int(n_)) for x, n_ in zip(X, nrm)] + [(-x, int(n_)) for x, n_ in zip(X, nrm)]
        psis = []
        # backtracking over the images of the kernel basis, checking inner products incrementally
        byn = {}
        for x, n_ in vecs:
            byn.setdefault(n_, []).append(np.array(x, dtype=np.int64))
        imgs = [None] * d_perp

        def bt(i):
            if i == d_perp:
                Am = np.array(imgs, dtype=np.int64)
                if abs(round(np.linalg.det(Am.astype(float)))) == 1:
                    psis.append(np.linalg.solve(Kp, Am.astype(float) @ Kp))
                return
            for x in byn.get(int(GK[i, i]), []):
                if all(int(x @ GK @ imgs[j]) == int(GK[i, j]) for j in range(i)):
                    imgs[i] = x
                    bt(i + 1)
            imgs[i] = None
        bt(0)
    else:
        Wp = np.zeros((0, 24)); psis = [np.zeros((0, 0))]
    mats = []
    Rcoef = Bf @ np.linalg.pinv(Sm)                                     # coefficients of the R-projection in simple roots
    for sol in sols:
        perm = [0] * rank
        for i, (j, q, _tab) in sol.items():
            for a in range(len(comps[i])):
                perm[comps[i][a]] = comps[j][q[a]]
        ImgR = np.zeros((24, rank))
        for k in range(rank):
            ImgR[:, perm[k]] += Rcoef[:, k]
        PhiR = ImgR @ Sm                                                # images of the R-parts
        for Psi in psis:
            if d_perp:
                Pp_c = Bf @ Wp.T                                        # d-coords of the perp parts
                PhiP = (Pp_c @ Psi) @ Wp if False else (Pp_c @ Psi) @ Wp
            else:
                PhiP = 0
            PhiB = PhiR + PhiP
            Mc = PhiB @ Binv
            if np.allclose(Mc, np.rint(Mc), atol=1e-6) and abs(abs(np.linalg.det(np.rint(Mc))) - 1) < 1e-6:
                Mi = np.rint(Mc).astype(np.int64)
                if not any(np.array_equal(Mi, X_) for X_ in mats):
                    mats.append(Mi)
    out = {'id': rec_['id'], 'roots': rec_['roots'], 'components': ncomp, 'glue_code_size': len(G),
           'gamma_order': len(mats), 'candidates_after_glue': len(sols), 'seconds': round(time.time() - t0, 1),
           'matrices': [m.tolist() for m in mats]}
    return out


if __name__ == '__main__':
    res = main()
    table = {L['id']: L for L in json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'borcherds_odd24.json')))}
    res['table_group'] = table[res['id']]['group']
    print(json.dumps({k: v for k, v in res.items() if k != 'matrices'}), flush=True)
    if len(sys.argv) > 2:
        json.dump(res, open(sys.argv[2], 'w'))
