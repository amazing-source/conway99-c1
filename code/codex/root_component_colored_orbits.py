"""Complete coloured component covers, with explicit relabelling generators.

For fixed colours, normalizing the two cross matchings to identity leaves
only simultaneous relabellings centralizing the first internal matching.
These are generated by individual pair flips and adjacent pair swaps.
Allowing colour permutations adds swaps of colours 1/2 and 0/1, followed
by renormalization. No graph automorphism is assumed: this classifies the
different labellings of a component when its embedding has not been fixed.

For TWO components on the same line, their colour permutations must be
coupled. One may normalize the first with colours, but the second must
use a colour-preserving cover (or retain every relative colour orientation).
These orbits cannot be used to delete fixed-Gram branches independently.
"""

import argparse
from collections import Counter,deque
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0,str(Path(__file__).resolve().parent))
from root_component_resources import limit_research_process,atomic_json_write


def orbit_cover(record,allow_colours):
    ps=[tuple(p) for p in record['cross_permutations']]
    ms=[tuple(tuple(e) for e in m) for m in record['internal_matchings']]
    pindex={p:i for i,p in enumerate(ps)};mindex={m:i for i,m in enumerate(ms)}
    n=len(ps[0]);mates=[]
    for matching in ms:
        m=[0]*n
        for a,b in matching:m[a]=b;m[b]=a
        mates.append(m)
    inverses=[tuple(p.index(i) for i in range(n)) for p in ps]
    flips=[]
    for j in range(n//2):
        f=list(range(n));f[2*j],f[2*j+1]=f[2*j+1],f[2*j];flips.append(f)
    for j in range(n//2-1):
        f=list(range(n))
        for k in range(2):f[2*j+k],f[2*j+2+k]=f[2*j+2+k],f[2*j+k]
        flips.append(f)
    def matching_index(m,f):
        return mindex[tuple(sorted(tuple(sorted((f[i],f[j]))) for i,j in enumerate(m) if i<j))]
    def relabel(p,ma,mb,f):
        inverse=[f.index(i) for i in range(n)]
        return (pindex[tuple(f[p[inverse[i]]] for i in range(n))],
                matching_index(ma,f),matching_index(mb,f))
    def neighbours(code):
        pi,a,b=code;p=ps[pi];inv=inverses[pi]
        for f in flips:yield relabel(p,mates[a],mates[b],f)
        if allow_colours:
            yield (pindex[inv],b,a)
            order=[i for pair in ms[a] for i in pair]
            f=[order.index(i) for i in range(n)]
            new_mate2=[inv[mates[b][p[i]]] for i in range(n)]
            yield relabel(inv,[i^1 for i in range(n)],new_mate2,f)
    valid={tuple(c) for c in record['component_code_triples']};unseen=set(valid);orbits=[]
    while unseen:
        seed=min(unseen);orbit={seed};queue=deque([seed]);unseen.remove(seed)
        while queue:
            code=queue.popleft()
            for other in neighbours(code):
                assert other in valid,('not_invariant',code,other)
                if other not in orbit:
                    assert other in unseen, 'Distinct orbits must not overlap.'
                    unseen.remove(other);orbit.add(other);queue.append(other)
        triangle_counts={sum(i==j for i,j in enumerate(ps[c[0]])) for c in orbit}
        assert len(triangle_counts)==1
        orbits.append({'representative':list(seed),'size':len(orbit),'triangles':triangle_counts.pop()})
    assert sum(o['size'] for o in orbits)==len(valid)
    return {'vertices':3*n,'allow_colour_permutations':allow_colours,'complete_code_count':len(valid),
            'orbit_count':len(orbits),'orbits':orbits,
            'triangle_histogram':dict(sorted(Counter(o['triangles'] for o in orbits).items())),
            'all_generator_images_in_source':True,'all_codes_covered_disjointly':True}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('tables',type=Path)
    p.add_argument('--sizes',type=int,nargs='+',default=[12,18])
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args();resources=limit_research_process(1)
    raw=args.tables.read_bytes();library=json.loads(raw);records=[]
    for record in library['records']:
        if record['vertices'] not in args.sizes:continue
        for colours in (False,True):
            result=orbit_cover(record,colours);records.append(result)
            atomic_json_write(args.output,{'scope':__doc__,'source_sha256':hashlib.sha256(raw).hexdigest(),
                                         'resources':resources,'records':records})
            print({k:v for k,v in result.items() if k!='orbits'},flush=True)
