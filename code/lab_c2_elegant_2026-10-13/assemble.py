def parse_E(h):
    out = collections.Counter()
    for k, n in h.items():
        a, b = [int(x) for x in k.strip("()").split(",")]; out[(a, b)] += n
    return out

def EK_summary(tel, nroots, h1, h2):
    et = parse_E(tel.get("E_pair_trap", {})); es = parse_E(tel.get("E_pair_search", {}))
    allE = et + es
    if not allE: return None
    C = 3 * nroots // 4 + 8 if (3 * nroots) % 4 == 0 else None
    Ks = {}
    for (a, b), n in allE.items(): Ks[C - a - b] = Ks.get(C - a - b, 0) + n
    srcK = {int(k): n for k, n in tel.get("search_K", {}).items()}
    out = {"K_plus_E1_plus_E2_constant": C, "pairs_with_E_telemetry": sum(allE.values()),
           "E_each_min": min(min(a, b) for a, b in allE), "E_each_max": max(max(a, b) for a, b in allE),
           "K_from_E_min": min(Ks), "K_from_E_max": max(Ks), "K_from_E_zero_pairs": Ks.get(0, 0),
           "K_searched_min": min(srcK) if srcK else None, "K_searched_max": max(srcK) if srcK else None,
           "E_pair_histogram_trap": {"%d,%d" % k: n for k, n in sorted(et.items())}, "E_pair_histogram_search": {"%d,%d" % k: n for k, n in sorted(es.items())}}
    if h1 is not None:
        out["4_abs_h1_minus_h2"] = 4 * abs(h1 - h2)
        out["law_K_ge_4|h1-h2|_holds_on_data"] = (min(Ks) >= 4 * abs(h1 - h2))
        if srcK: out["law_holds_on_searched_K"] = (min(srcK) >= 4 * abs(h1 - h2))
    return out

