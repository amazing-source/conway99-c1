"""Lab session, 2026-10-12. Is a vertex-transitive graph on 243 vertices a CAYLEY graph? Regular subgroups of Aut.
Aut is generated (aut_tools.aut_group), all its elements are listed (small groups only), a Sylow 3-subgroup P is taken
(elements of 3-power order when it is normal), and every subgroup of index 3 of P is tested for regularity (a regular
subgroup of order 243 is a 3-group; if it lies in P it is a maximal subgroup of P; other Sylow subgroups are conjugate).
For each regular subgroup: abelian or not, exponent, order of the centre and of the derived subgroup, element orders.
python regular_subgroups.py <edge file>          Memory: a few thousand permutations of 243 points."""
import sys, os, itertools, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aut_tools as T


def mul(a, b): return tuple(a[x] for x in b)                 # (a*b)(x) = a(b(x))
def inv(a):
    r = [0] * len(a)
    for i, x in enumerate(a): r[x] = i
    return tuple(r)
def order(a, ident):
    k = 1; b = a
    while b != ident: b = mul(b, a); k += 1
    return k
def generate(gens, ident):
    G = {ident}; frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                k = mul(h, g)
                if k not in G: G.add(k); new.append(k)
        frontier = new
    return G


if __name__ == "__main__":
    A = T.load(sys.argv[1]); n = len(A); ident = tuple(range(n))
    o, gens, base, sizes = T.aut_group(A); gens = [tuple(g) for g in gens]
    G = generate(gens, ident); assert len(G) == o
    ords = {g: order(g, ident) for g in G}
    P = {g for g in G if ords[g] in (1, 3, 9, 27, 81, 243)}
    print("|Aut| = %d; elements of 3-power order: %d; element orders in Aut: %s" % (o, len(P), sorted(collections.Counter(ords.values()).items())))
    if generate(list(P), ident) != P: raise SystemExit("the Sylow 3-subgroup is not normal: not handled")
    # Frattini subgroup of P: generated by cubes and commutators
    Pl = sorted(P); phi_gens = {mul(mul(g, g), g) for g in Pl}
    small = [g for g in gens if g in P] or Pl[:1]
    Pgens = []
    cur = {ident}
    for g in Pl:                                              # a generating set of P
        if g not in cur: Pgens.append(g); cur = generate(Pgens, ident)
        if len(cur) == len(P): break
    for a in Pgens:
        for b in Pl: phi_gens.add(mul(mul(a, b), mul(inv(a), inv(b))))
    Phi = generate(list(phi_gens), ident)
    print("Sylow 3-subgroup P: order %d, %d generators, Frattini subgroup of order %d (so %d maximal subgroups)" % (len(P), len(Pgens), len(Phi), (len(P) // len(Phi) - 1) // 2))
    # cosets of Phi: P/Phi elementary abelian; maximal subgroups = unions of cosets forming hyperplanes
    rep = {}
    cosets = []
    for g in Pl:
        if g in rep: continue
        c = {mul(g, f) for f in Phi}; idx = len(cosets); cosets.append(c)
        for x in c: rep[x] = idx
    q = len(cosets)                                           # 3^r
    tab = [[rep[mul(next(iter(cosets[i])), next(iter(cosets[j])))] for j in range(q)] for i in range(q)]
    e = rep[ident]
    def sub_gen(S):
        S = set(S) | {e}; ch = True
        while ch:
            ch = False
            for a in list(S):
                for b in list(S):
                    c = tab[a][b]
                    if c not in S: S.add(c); ch = True
        return frozenset(S)
    hyper = set()
    r = 0
    while 3 ** r < q: r += 1
    for comb in itertools.combinations(range(q), max(r - 1, 0)):
        S = sub_gen(comb)
        if len(S) == q // 3: hyper.add(S)
    print("maximal subgroups of P: %d" % len(hyper))
    seen = collections.Counter()
    for Hc in hyper:
        N = set().union(*[cosets[i] for i in Hc])
        regular = all(all(g[x] != x for x in range(n)) for g in N if g != ident)
        if not regular: seen["not regular"] += 1; continue
        Nl = list(N); ab = all(mul(a, b) == mul(b, a) for a in Nl[:40] for b in Nl)
        centre = sum(1 for a in Nl if all(mul(a, b) == mul(b, a) for b in Nl))
        der = generate([mul(mul(a, b), mul(inv(a), inv(b))) for a in Nl[:60] for b in Nl[:60]], ident)
        oc = tuple(sorted(collections.Counter(ords[g] for g in N).items()))
        seen[("REGULAR, order %d" % len(N), "abelian" if ab else "non-abelian", "centre %d" % centre, "derived subgroup (from 60x60 commutators) %d" % len(der), "element orders %s" % (oc,))] += 1
    for k, v in seen.items(): print("  %d x %s" % (v, k))
