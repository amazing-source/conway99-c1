"""Class-minimum test for an arbitrary seed (vertex set with fully known adjacency and q-values).

Residual (affine-37 branch, no integer 18/26, no affine 21): in the class of q the minima per level are
  level 0: 40, |1|: 35, |2|: 34, |3|: 37, |4|: 44
(mod-7 invariant + parity + sum<=norm + the excluded shells).  A seed is dead if the lattice generated by
{q_v : v in seed} u {1} contains, in the class of q, an element below these minima.
q_u . q_v = 2 - 7A_uv (u != v), |q_v|^2 = 23, q_v . 1 = 11, q . q_v = 6 - 7 q(v), |q|^2 = 37, q . 1 = 33.
"""
import os, subprocess
import numpy as np
import sympy as sp

MINS = {0: 40, 1: 35, 2: 34, 3: 37, 4: 44}
FP = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fp_enum")


def basis_indices(A):
    """indices of q_v (plus the vector 1, index n) forming a Z-basis of the lattice they generate.
    Uses the integer kernel of the Gram; each kernel relation must have a +-1 coefficient on a kept vector."""
    n = A.shape[0]
    G = np.zeros((n + 1, n + 1), dtype=np.int64)
    G[:n, :n] = 21 * np.eye(n, dtype=np.int64) + 2 - 7 * A
    G[:n, n] = G[n, :n] = 11; G[n, n] = 99
    ker = sp.Matrix(G).nullspace()
    keep = list(range(n + 1))
    rels = []
    for v in ker:
        den = sp.ilcm(*[x.q for x in v]); w = [int(x * den) for x in v]
        g = 0
        for x in w:
            g = sp.igcd(g, x)
        rels.append([x // g for x in w])
    # eliminate: for each relation pick a kept index with coefficient +-1, drop it, substitute into others
    rels = [np.array(r, dtype=object) for r in rels]
    dropped = []
    while rels:
        r = rels.pop(0)
        cand = [i for i in keep if abs(r[i]) == 1 and i != n]
        if not cand:
            cand = [i for i in keep if abs(r[i]) == 1]
        if not cand:
            raise ValueError("relation without unit coefficient: lattice basis needs HNF")
        i = cand[0]
        keep.remove(i); dropped.append(i)
        # substitute: v_i = -sign * sum_{j != i} r_j v_j ; other relations stay valid after removing i? recompute
        newrels = []
        for s in rels:
            if s[i] != 0:
                s = s - (s[i] * r[i]) * r  # r[i] = +-1 so r[i]^-1 = r[i]
            newrels.append(s)
        rels = newrels
    return keep, G


def lattice_basis(G, lin, levels, W=10**6):
    """Exact Z-basis (LLL-reduced) of the lattice generated by vectors with integer PSD Gram G (possibly singular).
    LLL on [I | W*G] gives a unimodular U whose first m-r rows span the saturated relation module; the last r rows
    map the generators onto a basis.  Returns (Gram, lin, levels) in an LLL-reduced basis."""
    from fpylll import IntegerMatrix, LLL, GSO
    m = G.shape[0]
    Mx = IntegerMatrix(m, 2 * m)
    for i in range(m):
        Mx[i, i] = 1
        for j in range(m):
            Mx[i, m + j] = int(W * G[i, j])
    LLL.reduction(Mx)
    rows = [[Mx[i, j] for j in range(2 * m)] for i in range(m)]
    rel = [r for r in rows if all(v == 0 for v in r[m:])]
    U = np.array([r[:m] for r in rows if any(v != 0 for v in r[m:])], dtype=object)
    r = len(U)
    assert r + len(rel) == m
    Gn = U.dot(G.astype(object)).dot(U.T)
    # Gram-LLL of the new basis
    Gi = IntegerMatrix.from_matrix([[int(x) for x in row] for row in Gn])
    Ui = IntegerMatrix.identity(r)
    Mg = GSO.Mat(Gi, U=Ui, gram=True)
    Mg.update_gso()
    LLL.Reduction(Mg)()
    V = np.array([[Ui[i, j] for j in range(r)] for i in range(r)], dtype=object)
    B = V.dot(U)
    Gk = B.dot(G.astype(object)).dot(B.T)
    lk = B.dot(np.array(lin, dtype=object)); vk = B.dot(np.array(levels, dtype=object))
    return (np.array(Gk, dtype=np.int64), np.array(lk, dtype=np.int64), np.array(vk, dtype=np.int64))


def class_min_violation(A, qvals, bound=43, return_all=False):
    """A: seed adjacency (numpy int), qvals: list of q-values on the seed.  Returns list of (level, norm) found
    below the residual minima (empty list = seed survives this test)."""
    n = A.shape[0]
    G = np.zeros((n + 1, n + 1), dtype=np.int64)
    G[:n, :n] = 21 * np.eye(n, dtype=np.int64) + 2 - 7 * A
    G[:n, n] = G[n, :n] = 11; G[n, n] = 99
    lin = np.zeros(n + 1, dtype=np.int64)
    lin[:n] = 6 - 7 * np.array(qvals); lin[n] = 33
    levels = [1] * n + [9]
    # necessary: Gram of the q_v (with 1) and K_S = 27I - 9A + J positive semidefinite
    if np.linalg.eigvalsh(G.astype(float)).min() < -1e-8:
        return [("PSD_qgram", None)]
    K = 27 * np.eye(n) - 9 * A + 1
    if np.linalg.eigvalsh(K).min() < -1e-8:
        return [("PSD_K", None)]
    Gk, lk, lev_coef = lattice_basis(G, lin, levels)
    mins = [MINS[i] for i in range(5)]
    inp = (f"{len(lk)}\n" + " ".join(map(str, Gk.flatten())) + "\n" + " ".join(map(str, lk)) + f"\n37 {bound}\n1\n"
           + " ".join(map(str, lev_coef)) + f"\n3 {len(mins)} {0 if return_all else 1}\n" + " ".join(map(str, mins)) + "\n")
    out = subprocess.run([FP], input=inp.encode(), capture_output=True, check=True)
    bad = []
    for line in out.stdout.decode().split("\n"):
        if line.strip():
            lev, val = map(int, line.split())
            bad.append((lev, val))
    return bad
