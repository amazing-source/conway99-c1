r"""Finish line (C), C1 27/09: y2 stage by weights (companion of y_pairs.py).  For a W(R)-dominant y1, enumerate y2 in U with
|y2|^2 = 7, (y1,y2) = 0, y2 W(R cap y1-perp)-dominant, and the exact filters:
  roots: never |(a,y1)| = |(a,y2)| = 2 (per component, before assembly), (a,y1)^2 + (a,y2)^2 <= 6;
  new roots: |(b,y2)| <= 3/2, never both 3/2;  norm 3: |(v,y2)| <= 3, never both 3.
Per component the projection of y2 is a weight of level <= 2 (a W-conjugate of a dominant level-<=2 weight), given by its label
vector; W(R cap y1-perp) is generated by the simple reflections at the zero labels of y1 (y1 dominant), so dominance = labels >= 0
there.  Assembly: DP on (glue class mod the row lattice of H, norm, (y1,y2)); rootless part by a small shifted enumeration."""
import math, time
from fractions import Fraction as F
import numpy as np
from envelope_trap import hnf_rows, inverse_exact
from y_pairs import root_system, level2_labels, enum_shift


def component_data(R):
    Sroots, comp, marks, A, P = root_system(R)
    data = []
    for cmp, mk in zip(comp, marks):
        Sc = Sroots[cmp]
        Ac = A[np.ix_(cmp, cmp)]
        Ainv = inverse_exact([[int(x) for x in row] for row in Ac])
        pos = []
        for p in P:
            coef = np.linalg.lstsq(Sc.T, p, rcond=None)[0]
            if np.allclose(Sc.T @ coef, p, atol=1e-6):
                pos.append(np.rint(coef).astype(np.int64))
        data.append({'idx': cmp, 'A': Ac.astype(np.int64), 'Ainv': Ainv, 'marks': list(mk), 'pos': np.array(pos)})
    return Sroots, data


def orbit_level2(A, marks):
    n = len(marks)
    out = set()
    for lab in level2_labels(marks):
        if lab in out:
            continue
        stack = [lab]
        out.add(lab)
        while stack:
            c = stack.pop()
            for j in range(n):
                if c[j] != 0:
                    d = tuple(c[k] - c[j] * int(A[j, k]) for k in range(n))
                    if d not in out:
                        out.add(d); stack.append(d)
    return out


class Y2Engine:
    def __init__(self, B, Gi, Bf, R, X3, Snew, max_orbit=2_000_000):
        self.Gi, self.Bf, self.R, self.X3, self.Snew = Gi, Bf, R, X3, Snew
        self.Sroots, comps = component_data(R)
        rank = len(self.Sroots)
        self.rank = rank
        M = np.rint(Bf @ self.Sroots.T).astype(np.int64)
        rows = [[int(M[i, j]) for j in range(rank)] + [int(i == t) for t in range(24)] for i in range(24)]
        Hh = hnf_rows(rows)
        self.V = [row[rank:] for row in Hh]
        self.Vk = [row[rank:] for row in Hh[rank:]]
        Hm = [row[:rank] for row in Hh[:rank]]
        self.Hinv = inverse_exact(Hm) if rank else []
        e = 1
        for row in self.Hinv:
            for x in row:
                e = e * x.denominator // math.gcd(e, x.denominator)
        self.e = e
        HinvE = [[int(x * e) for x in row] for row in self.Hinv]
        # fast exact path for emit (C1 27/09): integer numpy instead of Fraction sums (the Fraction sums were ~90% of the runtime)
        big = (max((abs(v) for row in HinvE for v in row), default=0) * max(rank, 1) * 64 > 2 ** 55 or
               max((abs(v) for row in self.V[:rank] for v in row), default=0) > 2 ** 40)
        dt = object if big else np.int64
        self.HinvE_np = np.array(HinvE, dtype=dt) if rank else None
        self.V_np = np.array([list(r) for r in self.V[:rank]], dtype=dt) if rank else None
        self.data = []
        for cd in comps:
            orb = orbit_level2(cd['A'], cd['marks'])
            if len(orb) > max_orbit:
                raise RuntimeError('orbit too large %d' % len(orb))
            C = np.array(sorted(orb), dtype=np.int8)                          # labels are small: 8x less memory than int64
            assert np.array_equal(C.astype(np.int64), np.array(sorted(orb), dtype=np.int64))
            den = 1
            for row in cd['Ainv']:
                for x in row:
                    den = den * x.denominator // math.gcd(den, x.denominator)
            AinvD = np.array([[int(x * den) for x in row] for row in cd['Ainv']], dtype=np.int64)
            nrmD = np.einsum('ij,jk,ik->i', C, AinvD, C)
            KC = (C @ cd['pos'].T).astype(np.int16)
            HE = np.array([[HinvE[j][k] % e for k in range(rank)] for j in cd['idx']], dtype=np.int64)
            cls = (C @ HE) % e
            self.data.append({'idx': cd['idx'], 'C': C, 'AinvD': AinvD, 'den': den, 'nrmD': nrmD, 'KC': KC,
                              'pos': cd['pos'], 'cls': cls})
        self.K = np.array(self.Vk, dtype=np.int64) if self.Vk else None
        if self.K is not None:
            self.GK = self.K @ np.array(Gi, dtype=np.int64) @ self.K.T
            self.Kf = self.K.astype(float) @ Bf
            self.GKf = self.GK.astype(float)
            # exact data for the rootless part (27/09 night): w = (k_i, y0) are integers, t = GK^-1 w = mf / den with
            # mf = adj w; the solutions depend only on (mf mod den, den * bound), so they are cached per lattice
            GKinv = inverse_exact([[int(v) for v in row] for row in self.GK.tolist()])
            den = 1
            for row in GKinv:
                for x in row:
                    den = den * x.denominator // math.gcd(den, x.denominator)
            self.Kden = den
            self.GKadj = np.array([[int(x * den) for x in row] for row in GKinv], dtype=np.int64)
            self.KG = self.K @ np.array(Gi, dtype=np.int64)
            self.Gint = np.array(Gi, dtype=np.int64)
            self._zcache = {}

    def labels_of(self, yf):
        c = np.rint(self.Sroots @ yf).astype(np.int64)
        return [c[d['idx']] for d in self.data]

    def pairs_for(self, y1f, t0=None, max_seconds=600, max_out=10 ** 6):
        """y2 candidates for a dominant y1. Batched exact version (27/09 night): the DP carries integer norms and (y1, y2)
        scaled by D = lcm of the component denominators (they were Fractions); the leaves of the walk are processed in
        batches (one integer matrix product for the H-lattice part); a 1-dim rootless part runs the same interval test as
        enum_shift inline; higher dims use enum_shift with a Cholesky factor computed once. The candidates come out in the
        same order as before, so the lists are identical."""
        rank, e = self.rank, self.e
        d1 = self.labels_of(y1f)
        D = 1
        for dd in self.data:
            D = D * dd['den'] // math.gcd(D, dd['den'])
        SEVEN = 7 * D
        per = []
        for dd, lam in zip(self.data, d1):
            C = dd['C']
            ok = np.ones(len(C), bool)
            zero = lam == 0
            if zero.any():
                ok &= (C[:, zero] >= 0).all(axis=1)
            klam = dd['pos'] @ lam
            two = np.abs(klam) == 2
            if two.any():
                ok &= ~(np.abs(dd['KC'][:, two]) == 2).any(axis=1)
            ipD = C @ (dd['AinvD'] @ lam)
            idx = np.nonzero(ok)[0]
            sc = D // dd['den']
            per.append({'nrm': [int(v) * sc for v in dd['nrmD'][idx]],
                        'ip': [int(v) * sc for v in ipD[idx]],
                        'cls': [tuple(int(x) for x in row) for row in dd['cls'][idx]], 'C': C[idx]})
        zero = tuple([0] * rank)
        add = lambda a, b: tuple((x + y) % e for x, y in zip(a, b))
        full_rank = self.K is None
        Fs = [{(zero, 0, 0)}]
        for p in per:
            nxt = set()
            for (cl, nr, ip) in Fs[-1]:
                for k in range(len(p['C'])):
                    t = nr + p['nrm'][k]
                    if t <= SEVEN:
                        nxt.add((add(cl, p['cls'][k]), t, ip + p['ip'][k]))
            Fs.append(nxt)
            if len(nxt) > 3_000_000:
                raise RuntimeError('DP too large')
        if full_rank:
            goodF = {s for s in Fs[-1] if s[0] == zero and s[1] == SEVEN and s[2] == 0}
        else:
            goodF = {s for s in Fs[-1] if s[0] == zero}
        good = [goodF]
        for k in range(len(per) - 1, -1, -1):
            cur = set()
            p = per[k]
            for (cl, nr, ip) in Fs[k]:
                for j in range(len(p['C'])):
                    t = nr + p['nrm'][j]
                    if t <= SEVEN and (add(cl, p['cls'][j]), t, ip + p['ip'][j]) in good[0]:
                        cur.add((cl, nr, ip)); break
            good.insert(0, cur)
        Fs = None
        out = []
        kept = []
        # flush size: the filters build (rows x |X3|) and (rows x |new roots|) float matrices; keep them near 32 MB
        FL = int(max(500, min(20000, 4_000_000 // max(1, len(self.X3), len(self.Snew)))))
        stats = {'raw': 0, 'after_newroots': 0, 'after_norm3': 0, 'after_roots': 0}
        stop = [False]
        Bf, V, Hinv = self.Bf, self.V, self.Hinv
        S = self.Snew
        P1 = np.abs(S @ y1f) if len(S) else None
        Q1 = np.abs(self.X3 @ y1f)
        A1 = self.R @ y1f if len(self.R) else None

        def flush():
            if not out:
                return
            Y2 = np.array(out, dtype=np.int64).reshape(-1, 24)
            out.clear()
            stats['raw'] += len(Y2)
            Y2f = Y2.astype(float) @ Bf
            keep = (np.abs(np.einsum('ij,ij->i', Y2f, Y2f) - 7) < 1e-6) & (np.abs(Y2f @ y1f) < 1e-6)
            if len(S):
                P2 = np.abs(Y2f @ S.T)
                keep &= (P2 <= 1.5 + 1e-9).all(axis=1)
                keep &= ~((P2 > 1.4) & (P1[None, :] > 1.4)).any(axis=1)
            stats['after_newroots'] += int(keep.sum())
            Q2 = np.abs(Y2f @ self.X3.T)
            keep &= (Q2 <= 3 + 1e-9).all(axis=1)
            keep &= ~((Q2 > 2.9) & (Q1[None, :] > 2.9)).any(axis=1)
            stats['after_norm3'] += int(keep.sum())
            if A1 is not None:
                A2 = Y2f @ self.R.T
                keep &= ((A1[None, :] ** 2 + A2 ** 2) <= 6 + 1e-9).all(axis=1)
            stats['after_roots'] += int(keep.sum())
            kept.extend(Y2[keep])

        ncomp = len(per)
        Kdim = 0 if self.K is None else len(self.K)
        if Kdim:
            Lc = np.linalg.cholesky(np.array(self.GK.tolist(), dtype=float))   # as in enum_shift, computed once
            dK = [float(Lc[i, i] ** 2) for i in range(Kdim)]
            QK = [[float(Lc[j, i] / Lc[i, i]) if j > i else 0.0 for j in range(Kdim)] for i in range(Kdim)]
        buf = []

        def rootless(A0):
            """the old emit_a0 on a batch of a0 rows, same order of the output"""
            if self.K is None:
                for a0 in A0:
                    out.append(a0)
                    if len(out) >= FL:
                        flush()
                return
            Y0 = A0.astype(float) @ Bf
            TT = np.linalg.solve(self.GKf, (Y0 @ self.Kf.T).T).T               # rows: tt = GK^-1 Kf y0
            BND = 7 - np.einsum('ij,ij->i', Y0, Y0) + np.einsum('ij,jk,ik->i', TT, self.GKf, TT)
            eps = 1e-7
            if Kdim == 1:
                k0 = self.Kf[0]
                d0 = dK[0]
                for r in range(len(A0)):
                    bound = float(BND[r])
                    if bound < -1e-9:
                        continue
                    rem = bound + eps
                    mid = float(-TT[r, 0])
                    sp = math.sqrt(max(rem, 0.0) / d0) + eps
                    y0 = Y0[r]
                    for xi in range(math.ceil(mid - sp), math.floor(mid + sp) + 1):
                        if rem - d0 * (xi - mid) ** 2 < -eps:
                            continue
                        v = y0 + float(xi) * k0
                        if abs(v @ v - 7) < 1e-6:
                            a = A0[r] + xi * self.K[0]
                            if abs((a.astype(float) @ Bf) @ y1f) < 1e-6:
                                out.append(a)
                    if len(out) >= FL:
                        flush()
                return
            den, cache = self.Kden, self._zcache
            Wm = A0 @ self.KG.T                                                # (k_i, y0), exact
            MF = Wm @ self.GKadj.T                                             # den * t
            Y0N = np.einsum('ij,jk,ik->i', A0, self.Gint, A0)                  # |y0|^2, exact
            BN = 7 * den - Y0N * den + np.einsum('ij,ij->i', Wm, MF)           # den * bound, exact
            for r in range(len(A0)):
                bn = int(BN[r])
                if bn < 0:
                    continue
                mf = MF[r]
                m = mf % den
                nsh = (mf - m) // den                                          # t = nsh + m / den
                key = (m.tobytes(), bn)
                zs = cache.get(key)
                if zs is None:
                    if len(cache) > 300000:
                        cache.clear()
                    zs = _enum_z(dK, QK, Kdim, -m / den, bn / den, m, den, bn, self.GK)
                    cache[key] = zs
                for z in zs:
                    a = A0[r] + (z - nsh) @ self.K
                    if abs((a.astype(float) @ Bf) @ y1f) < 1e-6:
                        out.append(a)
                if len(out) >= FL:
                    flush()

        def process():
            if not buf:
                return
            ch = np.array(buf, dtype=np.int64).reshape(len(buf), ncomp)
            buf.clear()
            nb = len(ch)
            if not rank:
                return rootless(np.zeros((nb, 24), dtype=np.int64))
            cvec = np.zeros((nb, rank), dtype=self.HinvE_np.dtype)
            for ci, (dd, p) in enumerate(zip(self.data, per)):
                cvec[:, dd['idx']] = p['C'][ch[:, ci]].astype(np.int64)
            num = cvec @ self.HinvE_np                                       # = e * (c . H^-1), exact integers
            if num.dtype == object:
                bad = np.array([any(int(v) % e for v in row) for row in num], dtype=bool)
                b1 = np.array([[int(v) // e for v in row] for row in num], dtype=object)
            else:
                bad = (num % e != 0).any(axis=1)
                b1 = num // e
            for r in np.nonzero(bad)[0]:                                     # never expected; the exact old path
                b1[r] = [int(sum(F(int(cvec[r, jj])) * Hinv[jj][k] for jj in range(rank))) for k in range(rank)]
            A0 = b1 @ self.V_np
            if A0.dtype == object:
                A0 = np.array([[int(v) for v in row] for row in A0], dtype=np.int64)
            rootless(A0.astype(np.int64))

        def walk(k, cl, nr, ip, choice):
            if stop[0]:
                return
            if len(kept) >= max_out or (t0 is not None and time.time() - t0 > max_seconds):
                stop[0] = True
                return
            if k == ncomp:
                buf.append(choice)
                if len(buf) >= 4096:
                    process()
                return
            p = per[k]
            g = good[k + 1]
            pn, pi, pc = p['nrm'], p['ip'], p['cls']
            for j in range(len(p['C'])):
                t = nr + pn[j]
                if t > SEVEN:
                    continue
                s2 = (add(cl, pc[j]), t, ip + pi[j])
                if s2 in g:
                    walk(k + 1, s2[0], t, s2[2], choice + [j])
        walk(0, zero, 0, 0, [])
        process()
        flush()
        info = dict(stats)
        info['truncated'] = stop[0]
        Y2k = np.array(kept, dtype=np.int64).reshape(-1, 24)
        return Y2k, info


def _enum_shift_pre(d, Q, n, center, bound, y0, Kf):
    """y_pairs.enum_shift with the Cholesky data (d, Q) of GK precomputed (same arithmetic, same order of the output)"""
    out, x, eps = [], [0] * n, 1e-7

    def rec(k, rem):
        s = sum(Q[k][j] * (x[j] - center[j]) for j in range(k + 1, n))
        mid = center[k] - s
        sp = math.sqrt(max(rem, 0.0) / d[k]) + eps
        for xi in range(math.ceil(mid - sp), math.floor(mid + sp) + 1):
            r2 = rem - d[k] * (xi - mid) ** 2
            if r2 < -eps:
                continue
            x[k] = xi
            if k == 0:
                v = y0 + np.array(x, dtype=float) @ Kf
                if abs(v @ v - 7) < 1e-6:
                    out.append(list(x))
            else:
                rec(k - 1, r2)
        x[k] = 0
    if bound < -1e-9:
        return []
    rec(n - 1, bound + eps)
    return out


def _enum_z(d, Q, n, center, bound, m, den, bn, GK):
    """integer z with (den z + m) GK (den z + m)^T == den * bn exactly (i.e. |z + m/den|^2_GK = bn/den): the Fincke-Pohst
    walk of enum_shift around center = -m/den (same order), with the final test in exact integers. Returns int64 rows."""
    out, x, eps = [], [0] * n, 1e-7
    target = den * bn

    def rec(k, rem):
        s = sum(Q[k][j] * (x[j] - center[j]) for j in range(k + 1, n))
        mid = center[k] - s
        sp = math.sqrt(max(rem, 0.0) / d[k]) + eps
        for xi in range(math.ceil(mid - sp), math.floor(mid + sp) + 1):
            r2 = rem - d[k] * (xi - mid) ** 2
            if r2 < -eps:
                continue
            x[k] = xi
            if k == 0:
                v = den * np.array(x, dtype=np.int64) + m
                if int(v @ GK @ v) == target:
                    out.append(np.array(x, dtype=np.int64))
            else:
                rec(k - 1, r2)
        x[k] = 0
    if bound < -1e-9:
        return out
    rec(n - 1, bound + eps)
    return out
