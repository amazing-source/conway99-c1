def grid_partitions(G, limit=200):
    n = len(G); gl = grids_list(G)
    m = cp_model.CpModel(); x = [m.NewBoolVar("") for _ in gl]
    at = [[] for _ in range(n)]
    for i, g in enumerate(gl):
        for p in g: at[p].append(i)
    for p in range(n): m.AddExactlyOne([x[i] for i in at[p]])
    Mi = np.zeros((len(gl), n), dtype=np.int64)
    for i, g in enumerate(gl): Mi[i, g] = 1
    E = Mi @ G @ Mi.T
    for i, j in np.argwhere(np.triu((E > 0) & (E < 9), 1)):
        if not (set(gl[i]) & set(gl[j])): m.AddBoolOr([x[i].Not(), x[j].Not()])
    sols = []
    class CB(cp_model.CpSolverSolutionCallback):
        def on_solution_callback(s_):
            sols.append([gl[i] for i in range(len(gl)) if s_.Value(x[i])])
            if len(sols) >= limit: s_.StopSearch()
    s = cp_model.CpSolver(); s.parameters.enumerate_all_solutions = True; s.parameters.max_time_in_seconds = 600
    s.Solve(m, CB())
    return sols


def analyse_partition(G, part, spread_lines):
    n = len(G); cell = {p: i for i, g in enumerate(part) for p in g}
    m = len(part)
    Q = np.zeros((m, m), dtype=np.int64)
    for i, g in enumerate(part):
        for j in range(m):
            if j != i and G[np.ix_(g, part[j])].sum(): Q[i, j] = 1
    spread_set = set(map(tuple, spread_lines)) if spread_lines else set()
    tri = triangles(G)
    # (a) fibre grids
    fibre = sum(1 for g in part if sum(1 for t in tri if set(t) <= set(g) and t in spread_set) == 3)
    # grid rulings: the two parallel classes of lines inside each grid
    def rulings(g):
        ls = [t for t in tri if set(t) <= set(g)]
        cls = []
        for l in ls:
            for c in cls:
                if not (set(l) & set(c[0])): c.append(l); break
            else: cls.append([l])
        return [frozenset(frozenset(l) for l in c) for c in cls]
    R = [rulings(g) for g in part]
    # matchings and (b)
    sigma = {}
    iso = 0; tot = 0
    for i in range(m):
        for j in range(m):
            if Q[i, j]:
                mp = {a: int(part[j][np.nonzero(G[a, part[j]])[0][0]]) for a in part[i]}
                sigma[(i, j)] = mp
                if i < j:
                    tot += 1
                    img = set()
                    for cls in R[i]:
                        img.add(frozenset(frozenset(mp[a] for a in l) for l in cls))
                    if img == set(R[j]): iso += 1
    # (c) lines over quotient triangles
    per_tri = collections.Counter()
    for t in tri:
        cs = frozenset(cell[p] for p in t)
        if len(cs) == 3: per_tri[cs] += 1
    qtri = [frozenset(c) for c in itertools.combinations(range(m), 3) if Q[c[0], c[1]] and Q[c[1], c[2]] and Q[c[0], c[2]]]
    dist = collections.Counter(per_tri.get(t, 0) for t in qtri)
    # (d) monodromy at grid 0: holonomies of closed walks 0 -> i -> j -> 0 and 0->i->0->... (generated by cycles)
    base = part[0]; idx = {a: k for k, a in enumerate(base)}
    # spanning tree transport
    parent = {0: None}; order = [0]; dq = collections.deque([0])
    while dq:
        u = dq.popleft()
        for v in range(m):
            if Q[u, v] and v not in parent: parent[v] = u; order.append(v); dq.append(v)
    T = {0: {a: a for a in base}}           # T[v]: base point -> point of grid v along tree path
    for v in order[1:]:
        u = parent[v]; T[v] = {a: sigma[(u, v)][T[u][a]] for a in base}
    inv = {v: {b: a for a, b in T[v].items()} for v in T}
    gens = []
    for u in range(m):
        for v in range(m):
            if Q[u, v] and parent.get(v) != u and parent.get(u) != v and u < v:
                h = [idx[inv[u][inv_v]] for inv_v in []] if False else None
                perm = [0] * 9
                for a in base:
                    b = inv[v][sigma[(u, v)][T[u][a]]]     # base -> u -> v -> back to base along tree
                    perm[idx[a]] = idx[b]
                gens.append(Permutation(perm))
    Mon = PermutationGroup(gens) if gens else PermutationGroup([Permutation(list(range(9)))])
    S9 = None
    # centraliser of Mon in Sym(9) by brute force over Sym(9) is too big; use: centraliser of a transitive group is
    # semiregular, compute directly by testing permutations commuting with generators via backtracking
    cent = centraliser_order(Mon, 9)
    return dict(fibre_grids=fibre, iso_matchings=f"{iso}/{tot}", lines_per_triangle=dict(dist),
                monodromy_order=Mon.order(), monodromy_transitive=Mon.is_transitive(), deck=cent)


def centraliser_order(Gp, n):
    gens = Gp.generators
    count = 0
    for img0 in range(n):          # backtracking on images, but n = 9: brute force over Sym(9) restricted
        pass
    # brute force: 9! = 362880 permutations, test commuting with generators
    ga = [g.array_form for g in gens]
    cnt = 0
    for p in itertools.permutations(range(n)):
        ok = True
        for g in ga:
            for a in range(n):
                if p[g[a]] != g[p[a]]: ok = False; break
            if not ok: break
        if ok: cnt += 1
    return cnt


