"""Anatomy of the equitable grid partitions of the known srg(243,22,1,2).
For every partition into 27 grids (quotient K_{9,9,9}):
  (a) are the grids unions of 3 lines of the (unique) regular spread ("fibre grids") ?
  (b) are the 9-point matchings between adjacent grids grid isomorphisms (preserve the two rulings) ?
  (c) how many transversal lines lie over each triangle of the quotient ?
  (d) monodromy group (generated by holonomies of closed walks in the quotient, as permutations of one grid) and its
      centraliser in Sym(9): the deck group of the grid cover.  Compare with Aut(Gamma).
Usage: python3 gridcover_anatomy.py GRAPH"""
import sys, itertools, collections, numpy as np
from ortools.sat.python import cp_model
from sympy.combinatorics import Permutation, PermutationGroup
from lib243 import *
